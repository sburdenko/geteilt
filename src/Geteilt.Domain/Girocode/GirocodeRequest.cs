namespace Geteilt.Domain.Girocode;

/// <summary>
/// Everything a Girocode carries. Assembled by the application from one line of a settlement plan.
/// </summary>
public sealed record GirocodeRequest
{
    /// <summary>Account holder as it should appear in the banking app.</summary>
    public required string BeneficiaryName { get; init; }

    public required string Iban { get; init; }

    public required decimal Amount { get; init; }

    /// <summary>Must be EUR — SEPA credit transfer has no other option.</summary>
    public required string Currency { get; init; }

    /// <summary>Payment reference. Generated by the application, see <see cref="EpcQrPayload.RemittanceFor"/>.</summary>
    public string Remittance { get; init; } = string.Empty;
}
